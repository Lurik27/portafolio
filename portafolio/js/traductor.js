function aplicarIdioma(lang) {
    const textos = traducciones[lang];
    if (!textos) return;

    // Cambia todos los textos marcados con data-i18n
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
        const clave = el.dataset.i18n;
        if (textos[clave] !== undefined) {
            el.innerHTML = textos[clave];
        }
    });

    // Idioma del documento y título de la pestaña
    document.documentElement.lang = lang;
    document.title = textos.titulo;

    // Marca como activos los botones del idioma elegido (header y menú móvil)
    document.querySelectorAll(".idioma").forEach(function (boton) {
        boton.classList.toggle("activo", boton.dataset.lang === lang);
    });

    try {
        localStorage.setItem("idioma", lang);
    } catch (e) {
        // si el navegador bloquea localStorage, simplemente no se guarda
    }
}

document.querySelectorAll(".idioma").forEach(function (boton) {
    boton.addEventListener("click", function () {
        aplicarIdioma(boton.dataset.lang);
    });
});

// Al cargar: usa el idioma guardado (o español por defecto)
let guardado = "es";
try {
    guardado = localStorage.getItem("idioma") || "es";
} catch (e) {}
aplicarIdioma(traducciones[guardado] ? guardado : "es");